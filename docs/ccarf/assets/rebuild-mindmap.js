#!/usr/bin/env node
/**
 * Regenerates mindmap-data.js from outline.txt.
 *
 * This bundle ships mindmap-data.js already built, so you do NOT need to run
 * this to use the mind map as-is. Run it only after you edit outline.txt
 * (add/remove/rename a branch) and want the viewer to pick up the change.
 *
 * One-time setup (needs Node.js):
 *   npm install markmap-lib --no-save
 *
 * Then, every time you edit outline.txt:
 *   node rebuild-mindmap.js
 */
const fs = require("fs");
const path = require("path");

let Transformer;
try {
  ({ Transformer } = require("markmap-lib"));
} catch (e) {
  console.error(
    "\nCouldn't find markmap-lib. Install it once with:\n\n  npm install markmap-lib --no-save\n\nthen re-run this script.\n"
  );
  process.exit(1);
}

// Plain Markdown, kept as .txt (not .md) on purpose — MkDocs treats every
// .md file under docs/ as a page to build, and this one is a data source,
// not a page.
const outlinePath = path.join(__dirname, "outline.txt");
const outPath = path.join(__dirname, "mindmap-data.js");

const md = fs.readFileSync(outlinePath, "utf8");
const transformer = new Transformer();
const { root, frontmatter } = transformer.transform(md);

const fm = (frontmatter && frontmatter.markmap) || {};
const meta = {
  initialExpandLevel: fm.initialExpandLevel ?? 1,
};

// Stamp every node under each top-level domain branch with that branch's index
// (0-4), so the viewer can color a whole branch by domain — deterministically,
// regardless of the order markmap's renderer happens to visit nodes in. This
// keeps every domain the same hue as its counterpart in the Study Runway page.
function stampDomain(node, idx) {
  node.payload = Object.assign({}, node.payload, { domainIndex: idx });
  (node.children || []).forEach((child) => stampDomain(child, idx));
}
(root.children || []).forEach((domainNode, i) => stampDomain(domainNode, i));

const banner =
  "// AUTO-GENERATED by rebuild-mindmap.js from outline.txt — do not hand-edit.\n";

fs.writeFileSync(
  outPath,
  banner +
    "window.__markmapData = " + JSON.stringify(root) + ";\n" +
    "window.__markmapMeta = " + JSON.stringify(meta) + ";\n"
);

console.log("Wrote " + outPath + " (" + fs.statSync(outPath).size + " bytes)");
